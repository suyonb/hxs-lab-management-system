MERGE INTO HXS_SYS_USER_ROLE target
USING (
    SELECT u.ID USER_ID, r.ID ROLE_ID FROM HXS_SYS_USER u CROSS JOIN HXS_SYS_ROLE r
    WHERE u.USER_NAME = 'admin' AND r.ROLE_CODE = 'admin'
) source
ON (target.USER_ID = source.USER_ID AND target.ROLE_ID = source.ROLE_ID)
WHEN NOT MATCHED THEN INSERT (ID, USER_ID, ROLE_ID, CREATE_TIME)
VALUES (SYS_GUID(), source.USER_ID, source.ROLE_ID, SYSTIMESTAMP);

MERGE INTO HXS_SYS_ROLE_MENU target
USING (
    SELECT r.ID ROLE_ID, m.ID MENU_ID FROM HXS_SYS_ROLE r CROSS JOIN HXS_SYS_MENU m
    WHERE r.ROLE_CODE = 'admin' AND m.MENU_CODE IN ('dashboard', 'sys', 'sys:user', 'sys:role', 'sys:menu', 'sys:org')
) source
ON (target.ROLE_ID = source.ROLE_ID AND target.MENU_ID = source.MENU_ID)
WHEN NOT MATCHED THEN INSERT (ID, ROLE_ID, MENU_ID, CREATE_TIME)
VALUES (SYS_GUID(), source.ROLE_ID, source.MENU_ID, SYSTIMESTAMP);

