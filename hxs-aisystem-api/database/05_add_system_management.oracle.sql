USING (SELECT 'root' ORG_CODE, '总部' ORG_NAME, 'company' ORG_TYPE FROM DUAL) source
ON (target.ORG_CODE = source.ORG_CODE)
WHEN MATCHED THEN UPDATE SET target.ORG_NAME = source.ORG_NAME, target.ORG_TYPE = source.ORG_TYPE, target.IS_ACTIVE = 1, target.UPDATE_TIME = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (ID, PARENT_ID, ORG_NAME, ORG_CODE, ORG_TYPE, SORT_NO, IS_ACTIVE, CREATE_TIME, UPDATE_TIME)
