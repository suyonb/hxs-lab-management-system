MERGE INTO HXS_SYS_MENU target
USING (
    SELECT 'sys:user' MENU_CODE, '用户管理' MENU_NAME, 'page' MENU_TYPE, '/system/users' ROUTE_PATH, 'system/user/index' COMPONENT, 'users' ICON, 'sys:user:list' PERMISSION_CODE, 10 SORT_NO FROM DUAL UNION ALL
    SELECT 'sys:role', '角色管理', 'page', '/system/roles', 'system/role/index', 'shield', 'sys:role:list', 20 FROM DUAL UNION ALL
    SELECT 'sys:menu', '菜单管理', 'page', '/system/menus', 'system/menu/index', 'menu', 'sys:menu:list', 30 FROM DUAL UNION ALL
    SELECT 'sys:org', '组织架构', 'page', '/system/orgs', 'system/org/index', 'building', 'sys:org:list', 40 FROM DUAL
