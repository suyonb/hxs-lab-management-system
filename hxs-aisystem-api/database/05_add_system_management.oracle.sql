MERGE INTO HXS_SYS_USER target
USING (
    SELECT
        'admin' USER_NAME,
        '系统管理员' DISPLAY_NAME,
        'PBKDF2-SHA256$100000$Z8FQdKYJmn+9Xni6Sw5pyw==$1FdRLFcdr36OalrfjPiGN9se2EDWrdSNwOkIWN31E5c=' PASSWORD_HASH,
        (SELECT ID FROM HXS_SYS_ORG WHERE ORG_CODE = 'root') ORG_ID
